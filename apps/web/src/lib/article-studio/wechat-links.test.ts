// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
// @ts-expect-error These functions are serialized into the editor tab by COSE.
import { fillWechatContent, saveWechatDraft } from '../../../../../vendor/cose/packages/core/src/platforms/wechat.js'

const source = '<section data-md-component="WeChatFigureV1"><a href="/media/report.png"><img src="https://mmbiz.qpic.cn/report.png" alt="报表"></a></section><p><a href="mailto:m@example.com"><strong>邮箱</strong></a> <a href="https://example.org">https://example.org</a><a name="section"></a></p><pre><code><span style="color:red">#,##0.00</span> &lt;a href="example"&gt;</code></pre><mpcpc data-id="original-ad"></mpcpc>'
let editor: HTMLElement
let saved: string[]

beforeEach(() => {
  vi.useFakeTimers()
  vi.stubGlobal('waitFor', async () => null)
  document.body.innerHTML = '<div class="title-editor__input"><div class="ProseMirror">标题</div></div><div class="ProseMirror" id="body-editor"></div><a href="https://source.test">原文链接</a><button>保存为草稿</button>'
  editor = document.getElementById('body-editor')!
  saved = []
  document.querySelector('button')!.onclick = () => { saved.push(editor.innerHTML) }
})

afterEach(() => {
  document.body.replaceChildren()
  vi.unstubAllGlobals()
  vi.useRealTimers()
})

it.each(['JSAPI', 'paste'])('unlinks the %s payload and cancels a topic generated by WeChat before saving', async (transport) => {
  function accept(html: string) {
    editor.innerHTML = html
    expect(editor.querySelector('a')).toBeNull()
    // WeChat recognizes the last #0 in an Excel number format after import.
    const token = editor.querySelector('code span')!
    token.innerHTML = '#,#<a class="wx_topic_link" data-topic="1">#0</a>.00'
    const topic = token.querySelector('a')!
    topic.onclick = () => {
      const cancel = document.createElement('button')
      cancel.textContent = '取消话题标签'
      cancel.getClientRects = () => [new DOMRect()] as unknown as DOMRectList
      cancel.onclick = () => { topic.replaceWith(...topic.childNodes); cancel.remove() }
      document.body.append(cancel)
    }
  }
  if (transport === 'JSAPI') {
    vi.stubGlobal('__MP_Editor_JSAPI__', { invoke({ apiParam, sucCb }: { apiParam: { content: string }, sucCb: () => void }) { accept(apiParam.content); sucCb() } })
  }
  else {
    vi.stubGlobal('DataTransfer', class extends Map<string, string> {
      setData(type: string, value: string) { this.set(type, value) }
      getData(type: string) { return this.get(type) ?? '' }
    })
    vi.stubGlobal('ClipboardEvent', class extends Event {
      constructor(type: string, init: ClipboardEventInit) {
        super(type, init)
        Object.assign(this, { clipboardData: init.clipboardData })
      }
    })
    editor.addEventListener('paste', event => accept(event.clipboardData!.getData('text/html')))
  }
  const fill = fillWechatContent('', source)
  await vi.runAllTimersAsync()
  expect(await fill).toMatchObject({ success: true, imageCount: 1 })
  expect(editor.querySelector('.wx_topic_link')?.textContent).toBe('#0')
  const save = saveWechatDraft('', null)
  await vi.runAllTimersAsync()
  expect(await save).toMatchObject({ success: true })
  expect(saved).toHaveLength(1)
  const draft = document.createElement('div')
  draft.innerHTML = saved[0]
  expect(draft.querySelector('a')).toBeNull()
  expect(draft.querySelector('[data-md-component] img')?.getAttribute('src')).toBe('https://mmbiz.qpic.cn/report.png')
  expect(draft.querySelector('strong')?.textContent).toBe('邮箱')
  expect(draft.querySelector('p')?.textContent).toBe('邮箱 https://example.org')
  expect(draft.querySelector('code')?.textContent).toBe('#,##0.00 <a href="example">')
  expect(draft.querySelector<HTMLElement>('code span')?.style.color).toBe('red')
  expect(draft.querySelector('mpcpc')?.getAttribute('data-id')).toBe('original-ad')
  expect(document.querySelector('a[href="https://source.test"]')?.textContent).toBe('原文链接')
})

it('does not click save if the editor still owns a topic and offers no unlink action', async () => {
  editor.setAttribute('data-cose-wechat-body', '')
  editor.innerHTML = '<p><a class="wx_topic_link">#0</a></p>'
  const result = saveWechatDraft('', null)
  await vi.runAllTimersAsync()
  expect(await result).toMatchObject({ success: false, error: expect.stringContaining('话题') })
  expect(saved).toEqual([])
  expect(editor.textContent).toBe('#0')
})

it.each([true, false])('only saves a late auto-link removal when the editor model accepts it (%s)', async (acceptEdit) => {
  editor.setAttribute('data-cose-wechat-body', '')
  editor.innerHTML = '<p><a href="mailto:m@example.com">m@example.com</a></p><mpcpc data-id="ad"></mpcpc>'
  let model = editor.cloneNode(true) as HTMLElement
  Object.assign(editor, { pmViewDesc: { view: {
    dom: editor,
    domObserver: { flush() { if (acceptEdit) model = editor.cloneNode(true) as HTMLElement } },
    state: { doc: { content: { size: 1 }, slice: () => model } },
    serializeForClipboard: (dom: HTMLElement) => ({ dom }),
  } } })
  const save = saveWechatDraft('', null)
  await vi.runAllTimersAsync()
  expect((await save).success).toBe(acceptEdit)
  expect(saved).toEqual(acceptEdit ? ['<p>m@example.com</p><mpcpc data-id="ad"></mpcpc>'] : [])
})
